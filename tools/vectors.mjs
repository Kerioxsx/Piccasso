// Shared conformance vectors: the JS engine computes them, the Rust engine must
// reproduce them (rust/crates/drawstep-core/tests/vectors.rs).
import { makeRGBA, toGray, blur2, sobel, colorSobel, otsu, foregroundFromBorder, cleanMask, labelComponents,
  traceBoundary, douglasPeucker, posterizeLevels, prepareImage, resizeBox, percentileThreshold } from '../web/js/core/image.js';
import { analyze } from '../web/js/core/analysis.js';
import { generateSteps } from '../web/js/core/steps.js';
import { renderStyle } from '../web/js/core/render.js';
import { homography, detectPaper, warpGray } from '../web/js/core/geometry.js';
import { defaultPrep } from '../web/js/core/project.js';

export function fnv1a(bytes) {
  let h = 0x811c9dc5;
  for (let i = 0; i < bytes.length; i++) { h ^= bytes[i]; h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
}

/** 48×36 synthetic scene: gradient background, dark disc, mid-gray box, thin line. */
export function vectorImage() {
  const W = 48, H = 36, img = makeRGBA(W, H);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    let r = 220 + Math.floor(x / 4), g = 215 + Math.floor(y / 4), b = 200;
    if ((x - 14) ** 2 + (y - 18) ** 2 < 81) { r = 60 + x; g = 40; b = 30 + y; }
    if (x >= 28 && x <= 40 && y >= 10 && y <= 27) { r = 90; g = 120; b = 170 - y; }
    if (y === 31 && x > 4 && x < 44) { r = 30; g = 30; b = 30; }
    const i = (y * W + x) * 4; img.data[i] = r; img.data[i + 1] = g; img.data[i + 2] = b; img.data[i + 3] = x === 0 && y === 0 ? 128 : 255;
  }
  return img;
}

export function computeVectors(shared) {
  const img = vectorImage();
  const W = img.width, H = img.height;
  const level = shared.difficulty.levels.intermediate;
  const g = toGray(img);
  const fg = foregroundFromBorder(img, 1);
  const m = cleanMask(fg.mask, W, H);
  const { labels, comps } = labelComponents(m, W, H);
  const big = comps.slice().sort((a, b) => b.area - a.area)[0];
  const trace = traceBoundary(labels, W, H, big.label, big.startX, big.startY);
  const prep = { ...defaultPrep(), crop: { x: 0.1, y: 0.05, w: 0.8, h: 0.9 }, rotation: 90, flipH: true, brightness: 10, contrast: 15, difficulty: 'intermediate' };
  const prepared = prepareImage(img, prep, 30);
  const analysis = analyze(img, level, {});
  const steps = generateSteps(analysis, { ...defaultPrep(), difficulty: 'intermediate' }, shared);
  const renders = {};
  for (const s of shared.styles.styles) {
    renders[s.id] = fnv1a(renderStyle(img, s.id, { level, analysisMaxDim: 320, lineThickness: 2, sketchContrast: 20, simplifyBackground: s.id === 'pencil_sketch' }).data);
  }
  const paperImg = { width: W, height: H, data: new Uint8Array(W * H) };
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) paperImg.data[y * W + x] = (x > 8 && x < 40 && y > 4 && y < 32 && x - 8 > (y - 4) / 4) ? 235 : 40;
  const paper = detectPaper(paperImg);
  return {
    note: 'Generated by tools/vectors.mjs from the JS engine. The Rust engine must match exactly (numbers within 2e-4).',
    image: { width: W, height: H, rgbaBase64: Buffer.from(img.data).toString('base64') },
    gray: fnv1a(g.data),
    blur2r2: fnv1a(blur2(g, 2).data),
    sobel: fnv1a(sobel(g).data),
    colorSobel: fnv1a(colorSobel(img, 1).data),
    otsu: otsu(g),
    percentile: percentileThreshold(sobel(g), 0.1, 20),
    foreground: { threshold: fg.threshold, separation: Math.round(fg.separation * 1000) / 1000, mask: fnv1a(fg.mask), dist: fnv1a(fg.dist.data), clean: fnv1a(m) },
    components: comps.map((c) => [c.label, c.area, c.minX, c.minY, c.maxX, c.maxY]),
    trace: trace,
    douglasPeucker: douglasPeucker(trace, 1.5, true),
    posterize4: fnv1a(posterizeLevels(blur2(g, 2), 4)),
    resize: fnv1a(resizeBox(img, 17, 11).data),
    prepared: { width: prepared.width, height: prepared.height, hash: fnv1a(prepared.data) },
    renders,
    homography: homography([[0, 0], [10, 0], [10, 10], [0, 10]], [[1, 2], [12, 1], [11, 13], [0, 9]]),
    paper,
    warp: fnv1a(warpGray(paperImg, paper.corners, 20, 16).data),
    analysis,
    steps,
  };
}
